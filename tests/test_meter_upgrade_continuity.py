#!/usr/bin/env python3
"""Test migration from the exact reviewed v6.0.11 meter to v6.0.13.

The test retains the actual JSON journal generated by OLD source, reloads it
under NEW source, and checks outage/replay/restart/reassignment behavior.
It never contacts Nexus or a live VPS. Strict signed-scope tests run separately.
"""
import copy
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch


CURRENT = Path(__file__).resolve().parents[1]
OLD_SHA = "647adcf7af326b205fce12545fb5d75a20bb8191"
OLD = Path(os.environ.get("XMESH_PREVIOUS_NODE_DIR", ".ci-previous-node")).resolve()


def load_guard(folder: Path, name: str):
    source = folder / "deploy/xmesh-policy-guard.py"
    if not source.is_file():
        raise AssertionError(f"Missing {name} policy guard")
    spec = importlib.util.spec_from_file_location(name, source)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def snapshot(module, ledger, allowed=None):
    with patch.object(module.base, "write_atomic") as writer, \
         patch.object(module.base.Path, "is_dir", return_value=True), \
         patch.object(module.base.grp, "getgrnam", side_effect=KeyError):
        if allowed is None:
            module.store_metrics_snapshot(ledger, 31, 2000)
        else:
            module.store_metrics_snapshot(ledger, 31, 2000, allowed)
    return json.loads(writer.call_args.args[1])


class UpgradeContinuity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        actual_sha = subprocess.check_output(
            ["git", "-C", str(OLD), "rev-parse", "HEAD"], text=True
        ).strip()
        assert actual_sha == OLD_SHA, (actual_sha, OLD_SHA)
        assert (OLD / "AGENT_VERSION").read_text().strip() == "control-v6.0.11"
        assert (CURRENT / "AGENT_VERSION").read_text().strip() == "control-v6.0.16"
        cls.previous = load_guard(OLD, "old_v6_0_11_guard")
        cls.current = load_guard(CURRENT, "current_v6_0_12_guard")

    def old_journal(self):
        # The OLD version has no assignment filter on publication.
        previous = self.previous
        ledger = previous.integrate_counters({}, {"7": 90, "8": 50},
                                              "old-xray-runtime", 1000, {
            ("7", "DE"): {"uplink": 40, "downlink": 20},
            ("7", "RETIRED"): {"uplink": 20, "downlink": 10},
            ("8", "DE"): {"uplink": 20, "downlink": 30},
        })
        old_payload = snapshot(previous, ledger)
        self.assertEqual({u["userId"] for u in old_payload["userTraffic"]}, {7, 8})
        self.assertIn((7, "RETIRED"), {
            (x["userId"], x["inboundTag"]) for x in old_payload["userInboundTraffic"]
        })
        return ledger

    def test_legacy_journal_offline_replay_restart_and_restored_assignment(self):
        journal = self.old_journal()
        before = copy.deepcopy(journal)
        with tempfile.TemporaryDirectory(prefix="xmesh-v6-meter-migration-") as root:
            # Source upgrade must NOT replace or clear the persisted journal.
            file = Path(root) / "policy-usage.json"
            file.write_text(json.dumps(journal, separators=(",", ":")))
            recovered = json.loads(file.read_text())
            self.assertEqual(recovered, before)

            current = self.current
            permitted = {7: {"DE"}}
            new = snapshot(current, recovered, permitted)
            self.assertEqual(new["userTraffic"], [
                {"userId": 7, "uplinkBytes": 60, "downlinkBytes": 30},
            ])
            self.assertEqual(new["userInboundTraffic"], [
                {"userId": 7, "inboundTag": "DE",
                 "uplinkBytes": 40, "downlinkBytes": 20},
            ])
            self.assertIn('[7,"RETIRED"]', recovered["inbounds"])
            self.assertIn('[8,"DE"]', recovered["inbounds"])

            # Simulate a lost Nexus response followed by a repeated collection:
            # no backend acknowledgements, no live network, and no new bytes.
            for stamp in (2100, 2200):
                recovered = current.integrate_counters(recovered, {"7": 90, "8": 50},
                    "old-xray-runtime", stamp, {
                        ("7", "DE"): {"uplink": 40, "downlink": 20},
                        ("7", "RETIRED"): {"uplink": 20, "downlink": 10},
                        ("8", "DE"): {"uplink": 20, "downlink": 30},
                    })
                self.assertEqual(snapshot(current, recovered, permitted), new)

            # A later Xray sample while the Nexus link is unavailable still
            # advances the *durable* ledger, even for now-unassigned user 8.
            recovered = current.integrate_counters(recovered, {"7": 125, "8": 60},
                "old-xray-runtime", 2300, {
                    ("7", "DE"): {"uplink": 60, "downlink": 25},
                    ("7", "RETIRED"): {"uplink": 20, "downlink": 10},
                    ("8", "DE"): {"uplink": 25, "downlink": 35},
                })
            catchup = snapshot(current, recovered, permitted)
            self.assertEqual(catchup["userTraffic"], [
                {"userId": 7, "uplinkBytes": 80, "downlinkBytes": 35},
            ])
            self.assertEqual(catchup["userInboundTraffic"], [
                {"userId": 7, "inboundTag": "DE",
                 "uplinkBytes": 60, "downlinkBytes": 25},
            ])
            file.write_text(json.dumps(recovered))
            # Simulate an agent process restart by reloading the JSON file.
            recovered = json.loads(file.read_text())
            self.assertEqual(snapshot(current, recovered, permitted), catchup)

            # A restarted Xray process may return small fresh counters.
            # The new runtime is a new epoch, not a negative subtraction.
            recovered = current.integrate_counters(recovered, {"7": 8},
                "restarted-xray-runtime", 2400, {
                    ("7", "DE"): {"uplink": 6, "downlink": 2},
                })
            after_restart = snapshot(current, recovered, permitted)
            self.assertEqual(after_restart["userTraffic"], [
                {"userId": 7, "uplinkBytes": 86, "downlinkBytes": 37},
            ])
            self.assertEqual(after_restart["userInboundTraffic"], [
                {"userId": 7, "inboundTag": "DE",
                 "uplinkBytes": 66, "downlinkBytes": 27},
            ])
            # Replaying identical sample after restart is idempotent.
            repeated = current.integrate_counters(recovered, {"7": 8},
                "restarted-xray-runtime", 2500, {
                    ("7", "DE"): {"uplink": 6, "downlink": 2},
                })
            self.assertEqual(snapshot(current, repeated, permitted), after_restart)

            # Reassignment can re-enable the historic user without erasing
            # old bytes, but must never leak those bytes before authorization.
            reauthorized = snapshot(current, repeated, {7: {"DE"}, 8: {"DE"}})
            self.assertEqual({row["userId"] for row in reauthorized["userTraffic"]}, {7, 8})
            restored_8 = next(row for row in reauthorized["userTraffic"]
                              if row["userId"] == 8)
            self.assertEqual((restored_8["uplinkBytes"], restored_8["downlinkBytes"]),
                             (25, 35))
            self.assertEqual(snapshot(current, repeated, permitted), after_restart)

    def test_v6_0_12_never_republishes_when_scope_is_missing(self):
        journal = self.old_journal()
        with self.assertRaisesRegex(ValueError, "signed telemetry scope"):
            self.current.store_metrics_snapshot(journal, 31, 1000, None)


if __name__ == "__main__":
    unittest.main()
